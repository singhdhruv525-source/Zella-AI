#!/usr/bin/env python3
# Writes sql/rollback/industry_2026_11_04_rollback.sql by comparing two isolated databases: one before the ten
# industry migrations and one after. The schema part is generated (functions with their grants, triggers, policies,
# views, new tables, columns, indexes, table and column grants); the data part (sql/rollback/industry_data_part.sql) is
# written by hand because it needs judgement: private values go back into record data, presets and record types come
# back from the backups taken before deploying, and tables holding records made after the deploy are kept, renamed.
# Usage: make_rollback.py <db before> <db after> <output file>     (isolated Postgres only)
import json, os, subprocess, sys

HOST = os.environ.get("ZPG_HOST", "/var/lib/postgresql/zella-sec")
PORT = os.environ.get("ZPG_PORT", "55433")
HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))

CATALOG = r"""
select json_build_object(
 'functions', (select json_object_agg(p.oid::regprocedure::text, json_build_object(
     'def', pg_get_functiondef(p.oid), 'src', md5(p.prosrc), 'kind', p.prokind,
     'acl', (select coalesce(json_agg(json_build_object('grantee', case when a.grantee = 0 then 'public' else a.grantee::regrole::text end, 'priv', a.privilege_type) order by 1), '[]')
               from aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) a)))
   from pg_proc p where p.pronamespace = 'public'::regnamespace),
 'triggers', (select coalesce(json_object_agg(c.relname || '.' || t.tgname, pg_get_triggerdef(t.oid)), '{}') from pg_trigger t join pg_class c on c.oid = t.tgrelid
   where not t.tgisinternal and c.relnamespace = 'public'::regnamespace),
 'policies', (select coalesce(json_object_agg(tablename || '.' || policyname, json_build_object('cmd', cmd, 'roles', roles, 'permissive', permissive, 'qual', qual, 'check', with_check)), '{}')
   from pg_policies where schemaname = 'public'),
 'views', (select coalesce(json_object_agg(c.relname, json_build_object('def', pg_get_viewdef(c.oid), 'opts', c.reloptions)), '{}') from pg_class c
   where c.relnamespace = 'public'::regnamespace and c.relkind = 'v'),
 'tables', (select json_agg(c.relname) from pg_class c where c.relnamespace = 'public'::regnamespace and c.relkind = 'r'),
 'columns', (select json_agg(table_name || '.' || column_name) from information_schema.columns where table_schema = 'public'),
 'indexes', (select json_object_agg(indexname, tablename) from pg_indexes where schemaname = 'public'),
 'table_grants', (select coalesce(json_agg(distinct table_name || '|' || grantee || '|' || privilege_type), '[]') from information_schema.role_table_grants
   where table_schema = 'public' and grantee in ('anon', 'authenticated', 'service_role', 'PUBLIC')),
 'column_grants', (select coalesce(json_agg(distinct table_name || '|' || column_name || '|' || grantee || '|' || privilege_type), '[]') from information_schema.column_privileges
   where table_schema = 'public' and grantee in ('anon', 'authenticated', 'service_role', 'PUBLIC')))
"""

def catalog(db):
    out = subprocess.run(["psql", "-h", HOST, "-p", PORT, "-U", "postgres", "-d", db, "-qtAX", "-c", CATALOG], check=True, capture_output=True, text=True).stdout
    return json.loads(out)

def q(ident):  # quote one identifier
    return '"' + ident.replace('"', '""') + '"' if not ident.replace("_", "").isalnum() or ident.lower() != ident else ident

def main(before, after, out):
    a, b = catalog(before), catalog(after)
    L = ["-- GENERATED by tests/staging/make_rollback.py from an isolated before/after pair. Do not edit by hand;",
         "-- the data part comes from sql/rollback/industry_data_part.sql. Runs as one transaction: all or nothing.",
         "-- Order: data back into place first (it needs the new tables and functions), then the schema.",
         "\\set ON_ERROR_STOP on", "begin;", ""]
    L.append(open(os.path.join(REPO, "sql", "rollback", "industry_data_part.sql")).read())
    L.append("\n-- ---------- schema (generated) ----------")

    # triggers added by the migrations
    for k in sorted(set(b["triggers"]) - set(a["triggers"])):
        tbl, name = k.split(".", 1)
        L.append(f"drop trigger if exists {q(name)} on public.{q(tbl)};")
    for k in sorted(set(a["triggers"]) & set(b["triggers"])):
        if a["triggers"][k] != b["triggers"][k]:
            tbl, name = k.split(".", 1)
            L.append(f"drop trigger if exists {q(name)} on public.{q(tbl)};\n{a['triggers'][k]};")
    # policies
    for k in sorted(set(b["policies"]) - set(a["policies"])):
        tbl, name = k.split(".", 1)
        L.append(f"drop policy if exists {q(name)} on public.{q(tbl)};")
    for k in sorted(set(a["policies"]) & set(b["policies"])):
        if a["policies"][k] != b["policies"][k]:
            raise SystemExit(f"policy changed in place, not handled: {k}")
    # views: recreate the previous definition (with its options) and its grants
    for v in sorted(set(a["views"]) & set(b["views"])):
        if a["views"][v] != b["views"][v]:
            opts = a["views"][v]["opts"]
            w = f" with ({', '.join(opts)})" if opts else ""
            L.append(f"drop view if exists public.{q(v)};\ncreate view public.{q(v)}{w} as\n{a['views'][v]['def'].rstrip().rstrip(';')};")
            for g in sorted(x for x in a["table_grants"] if x.split("|")[0] == v):
                _, grantee, priv = g.split("|")
                L.append(f"grant {priv.lower()} on public.{q(v)} to {grantee.lower()};")
    # functions changed in place: previous body, then previous grants exactly
    def acl_sql(sig, acl):
        s = [f"revoke all on function public.{sig} from public, anon, authenticated, service_role;"]
        for g in acl:
            if g["grantee"] in ("public", "anon", "authenticated", "service_role"):
                s.append(f"grant execute on function public.{sig} to {g['grantee']};")
        return s
    for sig in sorted(set(a["functions"]) & set(b["functions"])):
        fa, fb = a["functions"][sig], b["functions"][sig]
        if fa["src"] != fb["src"] or fa["def"] != fb["def"]:
            L.append(fa["def"].rstrip() + ";")
        if fa["src"] != fb["src"] or fa["acl"] != fb["acl"]:
            L += acl_sql(sig.replace("public.", "", 1) if sig.startswith("public.") else sig, fa["acl"])
    # functions added by the migrations
    for sig in sorted(set(b["functions"]) - set(a["functions"])):
        L.append(f"drop function if exists public.{sig.replace('public.', '', 1) if sig.startswith('public.') else sig} cascade;")
    # functions removed by the migrations (a signature replaced): restore
    for sig in sorted(set(a["functions"]) - set(b["functions"])):
        L.append(a["functions"][sig]["def"].rstrip() + ";")
        L += acl_sql(sig.replace("public.", "", 1) if sig.startswith("public.") else sig, a["functions"][sig]["acl"])
    # indexes added
    for ix in sorted(set(b["indexes"]) - set(a["indexes"])):
        if b["indexes"][ix] in a["tables"]:
            L.append(f"drop index if exists public.{q(ix)};")
    # columns added to existing tables
    for col in sorted(set(b["columns"]) - set(a["columns"])):
        tbl, c = col.split(".", 1)
        if tbl in a["tables"]:
            L.append(f"alter table public.{q(tbl)} drop column if exists {q(c)};")
    # table and column grants on existing tables and views
    existing = set(a["tables"]) | set(a["views"])
    for g in sorted(set(b["table_grants"]) - set(a["table_grants"])):
        t, grantee, priv = g.split("|")
        if t in existing: L.append(f"revoke {priv.lower()} on public.{q(t)} from {grantee.lower()};")
    for g in sorted(set(a["table_grants"]) - set(b["table_grants"])):
        t, grantee, priv = g.split("|")
        if t in existing: L.append(f"grant {priv.lower()} on public.{q(t)} to {grantee.lower()};")
    for g in sorted(set(b["column_grants"]) - set(a["column_grants"])):
        t, col, grantee, priv = g.split("|")
        if t in existing and (f"{t}|{grantee}|{priv}" not in a["table_grants"]):
            L.append(f"revoke {priv.lower()} ({q(col)}) on public.{q(t)} from {grantee.lower()};")
    # new tables: dropped when empty, otherwise kept under a clear name (handled in the data part via the helper)
    for t in sorted(x for x in set(b["tables"]) - set(a["tables"]) if not x.startswith("backup_20261104_")):
        L.append(f"select pg_temp.zella_rb_retire_table('{t}');")
    L += ["", "commit;", ""]
    with open(out, "w") as fh:
        fh.write("\n".join(L))
    print(f"wrote {out}: {len(L)} lines")

if __name__ == "__main__":
    if len(sys.argv) != 4: raise SystemExit(__doc__)
    main(*sys.argv[1:])
